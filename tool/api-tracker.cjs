// ---------------------------------------------------------------- previous Integrated/Tested
const existing = fs.existsSync(trackerFile) ? fs.readFileSync(trackerFile, 'utf8') : '';
const prev = {};
for (const line of existing.split('\n')) {
  const cells = line.split(/(?<!\\)\|/).map((c) => c.trim());
  if (cells.length >= 16 && /^\d+$/.test(cells[1])) prev[key(cells[3], cells[2].replace(/`/g, ''))] = { integrated: cells[13], tested: cells[14] };
}

// ---------------------------------------------------------------- table
const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const tags = [];
for (const o of ops) if (!tags.includes(o.tag)) tags.push(o.tag);
const head = '| # | Endpoint | Method | Frontend page | Frontend action | Path params | Query params | Request body | Expected success response | Expected error responses | Auth required | Permission/role required | Integrated (Y/N) | Tested (Y/N) | Notes |';
const lines = [head, '| ' + Array(15).fill('---').join(' | ') + ' |'];
let n = 0;
const counts = { total: 0, integrated: 0, tested: 0, critical: 0 };
for (const tag of tags) {
  lines.push(`| | **${esc(tag)}** | | | | | | | | | | | | | |`);
  for (const o of ops.filter((x) => x.tag === tag)) {
    n++;
    const k = key(o.method, o.path);
    let pages = dash[k] ? [...dash[k]].map((p) => `Dashboard: ${p}`) : [];
    if (!pages.length && planned[k]) pages = [...planned[k]].map((p) => `${p} (planned)`);
    if (!pages.length && manual[k]) pages = [manual[k].startsWith('None') ? manual[k] : `${manual[k]} (planned)`];
    const notes = [];
    if (critical.has(k)) notes.push('**Critical**');
    if (o.headers.length) notes.push(`Header ${o.headers.join(', ')}`);
    if (o.release === 'v1.1') notes.push('v1.1: do not build; API returns 404');
    if (o.internal) notes.push('Internal: not for apps');
    if (o.success.some((s) => s.listKey === 'items')) notes.push('List key `items`, not `data`');
    else if (o.success.some((s) => s.listKey === 'data')) notes.push('Cursor list `data`');
    if (requests[k]) notes.push(`Contract request ${requests[k]}`);
    if (extra[k]) notes.push(extra[k]);
    const integrated = (prev[k] && prev[k].integrated) || (dash[k] ? 'Y (dashboard)' : 'N');
    const tested = (prev[k] && prev[k].tested) || 'N';
    counts.total++;
    if (integrated.startsWith('Y')) counts.integrated++;
    if (tested.startsWith('Y')) counts.tested++;
    if (critical.has(k)) counts.critical++;
    lines.push(`| ${n} | \`${esc(o.path)}\` | ${o.method} | ${esc(pages.join('; ') || 'Not mapped')} | ${esc(o.summary)} | ${esc(o.pathParams.join(', ') || '-')} | ${esc(o.queryParams.join(', ') || '-')} | ${esc(o.body || '-')} | ${esc(o.success.map((s) => `${s.code}${s.schemaName ? ' ' + s.schemaName : ''}`).join('; '))} | ${esc(o.errors.map((e) => e.code).join(', ') + (o.codesInDesc.length ? ' (' + o.codesInDesc.map((c) => '`' + c + '`').join(', ') + ')' : ''))} | ${o.auth ? 'Yes (Bearer)' : 'No'} | ${esc(o.roles.join(', '))} | ${integrated} | ${tested} | ${esc(notes.join('. '))} |`);
  }
}
const summary = `Contract **${spec.info.version}**: ${counts.total} operations, ${counts.critical} critical. Integrated: **${counts.integrated}**. Tested: **${counts.tested}**.`;
const block = `${START}\n${summary}\n\n${lines.join('\n')}\n${END}`;
if (!existing.includes(START)) { console.error(`Markers not found in ${trackerFile}`); process.exit(1); }
fs.writeFileSync(trackerFile, existing.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block));
console.log(summary);
